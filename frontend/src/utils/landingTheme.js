const FALLBACK = THEMES.general

export function getLandingTheme(industrySlug) {
  return THEMES[industrySlug] || FALLBACK
}

export function getLandingLayout(industrySlug) {
  return getLandingTheme(industrySlug).layout
}

export function getLandingMotif(industrySlug) {
  return getLandingTheme(industrySlug).motifs
}

export function getLandingThemeStyle(industrySlug) {
  const theme = getLandingTheme(industrySlug)
  return {
    '--bl-display': theme.display,
    '--bl-body': theme.body,
    '--bl-ink': theme.ink,
    '--bl-paper': theme.paper,
    '--bl-surface': theme.surface,
    '--bl-forest': theme.forest,
    '--bl-forest-deep': theme.forestDeep,
    '--bl-gold': theme.gold,
    '--bl-nav-bg': theme.paper,
    '--bl-nav-bg-scrolled': theme.paper,
    '--bl-footer-bg': theme.paper,
    fontFamily: theme.body,
  }
}

