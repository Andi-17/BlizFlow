const STAT_VALUE_KEYS = {
  customers: 'customers_count',
  products: 'products_count',
  orders: 'orders_count',
  invoices: 'invoices_count',
  projects: 'projects_count',
  employees: 'employees_count',
  tasks: 'open_tasks_count',
  inventory: 'low_stock_count',
}

export function getIndustryPanel(slug) {
  return INDUSTRY_PANELS[slug] || INDUSTRY_PANELS.general
}

export function getStatValue(stats, key) {
  const field = STAT_VALUE_KEYS[key]
  if (!field || !stats) return 0
  return stats[field] ?? 0
}

export function getStatLabel(key, labelFn) {
  if (key === 'inventory') return `Low ${labelFn('inventory').toLowerCase()}`
  if (key === 'tasks') return `Open ${labelFn('tasks').toLowerCase()}`
  return labelFn(key)
}

export function resolveActionLabel(action, labelFn) {
  if (action.label) return action.label
  if (action.labelKey) {
    const entity = labelFn(action.labelKey)
    const singular = entity.endsWith('ies')
      ? `${entity.slice(0, -3)}y`
      : entity.endsWith('s')
        ? entity.slice(0, -1)
        : entity
    return `${action.labelPrefix || ''} ${singular}`.trim()
  }
  return 'Open'
}
